
import { useEffect, useState } from "react";
import {
  AlertTriangle,
  ShieldCheck,
  Clock,
  RefreshCw,
  FileText,
} from "lucide-react";

import api from "../services/api";

function ReviewFindings() {
  const [findings, setFindings] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const fetchFindings = async () => {
    setLoading(true);
    setError("");

    try {
      const response = await api.get("/review-findings/");

      const data = response.data;
      setFindings(Array.isArray(data) ? data : data.items || []);
    } catch (err) {
      setError(
        err.response?.data?.detail ||
        "Unable to load review findings."
      );
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchFindings();
  }, []);

  const severityClass = (severity) =>
    `finding-severity ${String(severity).toLowerCase()}`;

  const statusClass = (status) =>
    `finding-status ${String(status).toLowerCase()}`;

  return (
    <div className="page-content">
      <section className="welcome-section">
        <div>
          <div className="eyebrow">
            <ShieldCheck size={14} />
            BRAND COMPLIANCE
          </div>

          <h1>Review Findings</h1>

          <p>
            Examine detected compliance issues and recommended corrections.
          </p>
        </div>

        <button
          className="secondary-button"
          onClick={fetchFindings}
          disabled={loading}
        >
          <RefreshCw size={16} />
          Refresh
        </button>
      </section>

      <section className="stats-grid">
        <div className="stat-card">
          <div className="stat-icon">
            <FileText size={20} />
          </div>
          <h3>{findings.length}</h3>
          <strong>Total findings</strong>
          <p>Recorded findings</p>
        </div>

        <div className="stat-card">
          <div className="stat-icon">
            <AlertTriangle size={20} />
          </div>
          <h3>
            {findings.filter((f) => f.status === "OPEN").length}
          </h3>
          <strong>Open findings</strong>
          <p>Require attention</p>
        </div>

        <div className="stat-card">
          <div className="stat-icon">
            <Clock size={20} />
          </div>
          <h3>
            {findings.filter(
              (f) => f.verification_status === "UNVERIFIED"
            ).length}
          </h3>
          <strong>Unverified</strong>
          <p>Awaiting verification</p>
        </div>
      </section>

      <div className="panel findings-panel">
        <div className="panel-heading">
          <div>
            <h3>Detected compliance issues</h3>
            <p>Findings generated by the review engine</p>
          </div>
        </div>

        {loading ? (
          <div className="empty-state">
            Loading review findings...
          </div>
        ) : error ? (
          <div className="dashboard-error">{error}</div>
        ) : findings.length === 0 ? (
          <div className="empty-state">
            <div className="empty-icon">
              <ShieldCheck size={25} />
            </div>
            <h4>No findings available</h4>
            <p>Analyze a submission to generate review findings.</p>
          </div>
        ) : (
          <div className="findings-list">
            {findings.map((finding) => (
              <article className="finding-card" key={finding.id}>
                <div className="finding-card-header">
                  <div>
                    <span className="finding-id">
                      FINDING #{finding.id}
                    </span>
                    <h3>{finding.finding_type.replaceAll("_", " ")}</h3>
                    <span className="finding-submission">
                      Submission #{finding.submission_id}
                    </span>
                  </div>

                  <span className={severityClass(finding.severity)}>
                    {finding.severity}
                  </span>
                </div>

                <div className="finding-description">
                  <strong>What was detected?</strong>
                  <p>{finding.description}</p>
                </div>

                {finding.evidence && (
                  <div className="finding-description">
                    <strong>Evidence</strong>
                    <p>{finding.evidence}</p>
                  </div>
                )}

                <div className="finding-description">
                  <strong>Suggested correction</strong>
                  <p>{finding.suggested_fix || "No suggestion provided."}</p>
                </div>

                <div className="finding-meta">
                  <span>
                    Verification: {finding.verification_status}
                  </span>

                  <span className={statusClass(finding.status)}>
                    {finding.status}
                  </span>
                </div>

                <div className="finding-source">
                  Source: {finding.source_reference || "Not provided"}
                </div>
              </article>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}

export default ReviewFindings;
